import sys
from pathlib import Path
sys.path.insert(0, "src")

from saw_map.formats.map_reader import MapReader
from saw_map.assets.loader import AssetLoader
from saw_map.rendering.draw_order import DrawOrderStrategy

game_dir = Path("Research/SSI/Soldiers at War")
map_path = game_dir / "Single_g" / "Airfield.map"
doc = MapReader.parse_map(map_path)
loader = AssetLoader(game_dir)
tileset = loader.load_tileset("Airfield")
palette = loader.load_palette("Win.pal")

items = DrawOrderStrategy.generate_render_list(doc, tileset=tileset, max_layer=6)

valid_items = [it for it in items if it.asset_name is not None]
missing_items = [it for it in items if it.asset_name is None]

print(f"Total items generated by DrawOrderStrategy: {len(items)}")
print(f"Items with valid asset_name: {len(valid_items)}")
print(f"Items with missing asset_name (draws green placeholder): {len(missing_items)}")

from collections import Counter
missing_by_type = Counter(it.component_type.name for it in missing_items)
print(f"Missing items by component type: {missing_by_type}")

valid_by_type = Counter(it.component_type.name for it in valid_items)
print(f"Valid items by component type: {valid_by_type}")
